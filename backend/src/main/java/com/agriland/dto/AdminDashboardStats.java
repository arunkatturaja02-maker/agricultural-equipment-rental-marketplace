package com.agriland.dto;

public class AdminDashboardStats {
    private long totalUsers;
    private long totalCustomers;
    private long totalSellers;
    private long totalVehicles;
    private long totalLands;
    private long totalHouses;
    private long totalBookings;
    private long totalInquiries;
    private long totalSiteVisits;

    public AdminDashboardStats() {}

    public long getTotalUsers() {
        return totalUsers;
    }

    public void setTotalUsers(long totalUsers) {
        this.totalUsers = totalUsers;
    }

    public long getTotalCustomers() {
        return totalCustomers;
    }

    public void setTotalCustomers(long totalCustomers) {
        this.totalCustomers = totalCustomers;
    }

    public long getTotalSellers() {
        return totalSellers;
    }

    public void setTotalSellers(long totalSellers) {
        this.totalSellers = totalSellers;
    }

    public long getTotalVehicles() {
        return totalVehicles;
    }

    public void setTotalVehicles(long totalVehicles) {
        this.totalVehicles = totalVehicles;
    }

    public long getTotalLands() {
        return totalLands;
    }

    public void setTotalLands(long totalLands) {
        this.totalLands = totalLands;
    }

    public long getTotalHouses() {
        return totalHouses;
    }

    public void setTotalHouses(long totalHouses) {
        this.totalHouses = totalHouses;
    }

    public long getTotalBookings() {
        return totalBookings;
    }

    public void setTotalBookings(long totalBookings) {
        this.totalBookings = totalBookings;
    }

    public long getTotalInquiries() {
        return totalInquiries;
    }

    public void setTotalInquiries(long totalInquiries) {
        this.totalInquiries = totalInquiries;
    }

    public long getTotalSiteVisits() {
        return totalSiteVisits;
    }

    public void setTotalSiteVisits(long totalSiteVisits) {
        this.totalSiteVisits = totalSiteVisits;
    }
}
